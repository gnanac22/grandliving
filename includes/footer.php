// --- Architectural Atelier Menu Toggle ---
(function() {
  var hamburger = document.getElementById('navHamburger');
  var mobile = document.getElementById('navMobile');
  if (!hamburger || !mobile) return;
  
  hamburger.addEventListener('click', function() {
    var isOpen = hamburger.getAttribute('aria-expanded') === 'true';
    var nextState = !isOpen;
    hamburger.setAttribute('aria-expanded', nextState);
    mobile.classList.toggle('is-open', nextState);
    mobile.setAttribute('aria-hidden', !nextState);
    document.body.classList.toggle('is-menu-open', nextState);
    document.body.style.overflow = nextState ? 'hidden' : '';
  });
  
  // Close on link click
  mobile.querySelectorAll('a').forEach(function(link) {
    link.addEventListener('click', function() {
      hamburger.setAttribute('aria-expanded', 'false');
      mobile.classList.remove('is-open');
      mobile.setAttribute('aria-hidden', 'true');
      document.body.classList.remove('is-menu-open');
      document.body.style.overflow = '';
    });
  });
  
  // Close on ESC
  document.addEventListener('keydown', function(e) {
    if (e.key === 'Escape' && mobile.classList.contains('is-open')) {
      hamburger.click();
    }
  });
})();

